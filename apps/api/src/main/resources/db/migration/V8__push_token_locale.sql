-- 푸시 알림을 받는 사람의 말을 기억한다 (SOMA-544).
--
-- 분석 완료 알림은 예약 작업이 보낸다. 그 자리엔 요청이 없어서 받는 사람이 어느 말을
-- 쓰는지 알 길이 없고, 그대로 두면 영어로 쓰는 사람에게도 한국어 알림이 간다.
--
-- 앱이 토큰을 맡길 때는 요청이므로 그때 말을 함께 저장해 둔다. 보낼 때 그 값을 읽는다.
-- 이미 있는 토큰은 전부 한국어 사용자다 — 기본값으로 그대로 살린다.
ALTER TABLE push_tokens
    ADD COLUMN IF NOT EXISTS locale text NOT NULL DEFAULT 'ko';
